"""

operador    função
+           soma 
-           subtração
*           multiplicação
/           divisão
//          divisão inteira
%           resto divisão
**          potencia

"""
num1 = int(input("Digite um número: "))
num2 = int(input("Digite um número: "))

soma = num1 + num2 
print(soma)

subtracao = num1 - num2
print(subtracao)

multiplicacao = num1 * num2
print(multiplicacao)

divisao = num1 / num2
print(divisao)

divinteira = num1 // num2
print(divinteira)

resto = num1 % num2
print(resto)

potencia = num1 ** num2
print(potencia)
